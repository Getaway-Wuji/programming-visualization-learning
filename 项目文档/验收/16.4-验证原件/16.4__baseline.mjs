if(external.sha256!=='709c620f3300703138b4d1de0e96c2912a6091c3305319e87a5c8d3a6e6ec75c')throw Error('External handoff changed');
const result={task:'16.4',owner:'root / 完成16任务',date:new Date().toISOString(),head:git('rev-parse','HEAD'),branch:git('branch','--show-current'),staged:git('diff','--cached','--name-only'),outgoing:git('rev-list','--count','origin/main..HEAD'),prior,external,files};
