import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
const git=(...args)=>execFileSync('git',args,{encoding:'utf8'}).trim();
const sha=path=>createHash('sha256').update(readFileSync(path)).digest('hex');
const proof=path=>({path,sha256:sha(path)});
mkdirSync('.artifacts/16.4',{recursive:true});
const files=git('ls-files','--cached','--others','--exclude-standard','-z').split('\0').filter(Boolean).map(proof);
const prior=[...['16.1','16.2','16.3'].map(task=>`项目文档/验收/${task}-验证原件/index.json`),'项目文档/验收/16.3-最终复核.json','.artifacts/16.3/evidence-final.json',...['35','36','37','38'].map(v=>`content/c/p0/blockly-release-1.0.${v}.json`)].map(proof);
