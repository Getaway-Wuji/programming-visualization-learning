import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { format } from 'prettier';
import { inspectContentDraft } from '../web/src/content/validator.mjs';
const root = new URL('../', import.meta.url);
const bytes = await readFile(new URL('content/c/p0/course-1.0.1.json', root));
const sha256 = (value) => createHash('sha256').update(value).digest('hex');
const sourceSha256 = sha256(bytes);
if (sourceSha256 !== '713133313e65ba9ea000daa18d5feaea84beeb65f296b8102edc5de114fa2611')
  throw new Error('09.1 reviewed course changed; register a new reading release before building.');
const content = inspectContentDraft(bytes);
const base = (entity) => ({
  ref: { id: entity.id, version: entity.version },
  learningRevision: entity.learningRevision,
  acceptedPriorVersions: entity.acceptedPriorVersions,
});
// This is a separate, limited reading artifact. It grants no execution/judgement/asset publication.
const reading = {
  readingVersion: '1.0.0',
  sourceSha256,
  packageRef: { id: content.packageId, version: content.packageVersion },
  chapters: content.chapters,
  lessons: content.lessons,
  programs: content.programs,
  knowledgePoints: content.knowledgePoints,
  exercises: content.exercises.map(({ id, version, title, lessonRef, prompt }) => ({
    id,
    version,
    title,
    lessonRef,
    prompt,
  })),
  cases: content.cases.map(({ id, version, title }) => ({ id, version, title })),
  catalog: {
    purpose: 'lesson-reading',
    packageRef: { id: content.packageId, version: content.packageVersion },
    lessons: content.lessons.map((entity) => ({
      ...base(entity),
      requiredExerciseRefs: entity.requiredExerciseRefs,
    })),
    exercises: content.exercises.map((entity) => ({
      ...base(entity),
      lessonRef: entity.lessonRef,
      caseKeys: entity.tests.map((test) => test.caseKey),
    })),
    cases: content.cases.map(base),
  },
};
const output = Buffer.from(JSON.stringify(reading, null, 2) + '\n');
const destination = new URL('web/public/content/reading/', root);
await mkdir(destination, { recursive: true });
await writeFile(new URL('course-reading-1.0.0.json', destination), output);
const manifest = {
  readingVersion: '1.0.0',
  file: 'content/reading/course-reading-1.0.0.json',
  sha256: sha256(output),
  bytes: output.length,
  sourceSha256,
  capabilities: ['lesson.started', 'lesson.study-confirmed'],
  fullContentPublication: false,
};
await writeFile(new URL('manifest.json', destination), JSON.stringify(manifest, null, 2) + '\n');
await writeFile(
  new URL('web/src/content/reading-release.generated.ts', root),
  await format(
    '// Generated by build-reading.mjs from reviewed public lesson material.\nexport const readingRelease = ' +
      JSON.stringify(manifest) +
      ' as const;\n',
    { parser: 'typescript', singleQuote: true, printWidth: 100 },
  ),
);
console.log('09.2 reading release: six reviewed lessons; only started/confirmed capabilities.');
