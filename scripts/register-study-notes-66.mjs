import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, existsSync, mkdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';
import { studyNotesPaths } from './study-notes-release-inputs.mjs';
const dir = '.artifacts/20.1',
  target = 'content/c/p0/blockly-release-1.0.66.json',
  priorPath = 'content/c/p0/blockly-release-1.0.65.json';
const read = (p) => readFileSync(p),
  json = (p) =>
    JSON.parse(
      read(p)
        .toString()
        .replace(/^\uFEFF/, ''),
    );
const sha = (b) => createHash('sha256').update(b).digest('hex'),
  proof = (p) => ({ path: p, sha256: sha(read(p)) });
const save = (p, v) => writeFileSync(p, JSON.stringify(v, null, 2) + '\n', { flag: 'wx' });
assert.equal(existsSync(target), false);
const prior = json(priorPath),
  units = json(`${dir}/unit-full-r1.json`),
  browser = json(`${dir}/r201-candidate-smoke-r2.json`);
assert.equal(
  sha(read(priorPath)),
  json('项目文档/验收/发布凭据/19.4-1.0.65/index.json').registration.sha256,
);
assert.equal(units.success, true);
assert.equal(units.numPassedTests, 2154);
assert.equal(units.numFailedTests + units.numPendingTests, 0);
assert.equal(browser.stats.expected, 1);
assert.equal(browser.stats.unexpected + browser.stats.skipped + browser.stats.flaky, 0);
assert.deepEqual(browser.errors, []);
for (const p of ['type-final.log', 'lint-final.log']) assert.equal(read(`${dir}/${p}`).length, 0);
assert.match(
  read(`${dir}/format-final.log`).toString(),
  /All matched files use Prettier code style/,
);
for (const [key, p] of [
  ['engine', 'web/src/generated/c_viz_wasm_bg.wasm'],
  ['memoryEngine', 'web/src/generated/memory/c_viz_memory_bg.wasm'],
  ['algorithmEngine', 'web/src/generated/algorithm/c_viz_algorithm_bg.wasm'],
  ['advancedEngine', 'web/src/generated/advanced/c_viz_advanced_bg.wasm'],
  ['generatorEngine', 'web/src/generated/practice/c_viz_practice_bg.wasm'],
])
  assert.equal(sha(read(p)), prior[key].wasmSha256);
const sources = studyNotesPaths.map(proof),
  latest = Math.max(...studyNotesPaths.map((p) => statSync(p).mtimeMs));
// The complete build can rewrite identical generated bytes while units run.
// An unchanged prior registered blob proves identity; changed sources must predate units.
const rebuiltUnchanged = sources.filter((e) => statSync(e.path).mtimeMs > units.startTime);
for (const entry of rebuiltUnchanged)
  assert.equal(
    entry.sha256,
    prior.files.find((e) => e.path === entry.path)?.sha256,
    `Changed source after unit start: ${entry.path}`,
  );
assert.ok(Date.parse(browser.stats.startTime) >= latest, 'Browser smoke predates source');
const review = {
  task: '20.1',
  sources,
  frontendPassed: 2154,
  candidateChromePassed: 1,
  quality: { type: 0, lint: 0, format: 0 },
  scope:
    'Explicit local-only note selection, exact version provenance, session-only real snapshot capture and read-only preview; no download, persistence or AI changes.',
  limitations:
    'Source registration after full frontend and candidate capture smoke. Full formal record/preview/native-storage browser checks remain pending and are not claimed by this registration. Candidate seven-case failed attempt retained: unregistered learning capability is correctly unavailable.',
  taskAccepted: false,
  rebuiltUnchangedAfterUnitStart: rebuiltUnchanged,
};
save(`${dir}/release-review66.json`, review);
const archive = '项目文档/验收/发布凭据/20.1-1.0.66';
mkdirSync(archive, { recursive: true });
const evidence = {},
  files = [];
for (const name of ['unit-full-r1.json', 'r201-candidate-smoke-r2.json', 'release-review66.json']) {
  const file = `${name}.gz`,
    path = `${dir}/${file}`,
    bytes = gzipSync(read(`${dir}/${name}`));
  writeFileSync(path, bytes, { flag: 'wx' });
  writeFileSync(`${archive}/${file}`, bytes, { flag: 'wx' });
  const entry = proof(path);
  evidence[name.replace(/[^a-zA-Z]/g, '')] = entry;
  files.push({ ...entry, file });
}
save(target, {
  ...prior,
  releaseVersion: '1.0.66',
  registeredAt: '2026-11-01',
  reviewedAtUtc: new Date().toISOString(),
  supersedes: { version: '1.0.65', ...proof(priorPath) },
  scope: review.scope,
  reason:
    '2154 frontend tests, candidate real C++ capture smoke, types/lint/format and full build; formal note workflow acceptance follows separately.',
  evidenceFreshness: {
    latestSourceAt: new Date(latest).toISOString(),
    frontendPassed: 2154,
    candidateUniquePassed: 1,
  },
  files: sources,
  evidence,
});
save(`${archive}/index.json`, { version: '1.0.0', registration: proof(target), files });
const frozen = `${dir}/sources-66`;
mkdirSync(frozen, { recursive: true });
const frozenFiles = sources.map((e, i) => {
  const file = `${String(i).padStart(4, '0')}.gz`;
  writeFileSync(`${frozen}/${file}`, gzipSync(read(e.path)), { flag: 'wx' });
  return { ...e, file };
});
save(`${frozen}/index.json`, { registration: proof(target), files: frozenFiles });
console.log(JSON.stringify({ registered: '1.0.66', sources: sources.length, taskAccepted: false }));
